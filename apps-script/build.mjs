import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';

export function buildAppsScript() {
  const accounting = readFileSync(new URL('../src/lib/accounting.js', import.meta.url), 'utf8')
    .replaceAll('export function ', 'function ')
    .replaceAll('.at(-1)', '.slice(-1)[0]');
  const adapter = readFileSync(new URL('./snapshot.gs', import.meta.url), 'utf8');
  const reconciliation = readFileSync(new URL('../src/lib/reconciliation.js', import.meta.url), 'utf8')
    .replaceAll('export function ', 'function ');
  const portfolio = readFileSync(new URL('../src/lib/portfolio.js', import.meta.url), 'utf8')
    .replace("import { activeReconciliation, tradeCashTotals } from './reconciliation.js';", 'const { activeReconciliation, tradeCashTotals } = SnapshotReconciliation;')
    .replaceAll('export function ', 'function ');
  const snapshot = readFileSync(new URL('../src/lib/snapshot.js', import.meta.url), 'utf8')
    .replace("import { summarizeCashFlows, calculateUnitAccounting } from './accounting.js';",
      'const { summarizeCashFlows, calculateUnitAccounting } = SnapshotAccounting;')
    .replace("import { calculatePortfolio } from './portfolio.js';", 'const { calculatePortfolio } = SnapshotPortfolio;')
    .replace("import { activeReconciliation } from './reconciliation.js';", 'const { activeReconciliation } = SnapshotReconciliation;')
    .replaceAll('export function ', 'function ');
  return `// Generated by npm run build:snapshot. Contains no Firebase credentials.\n` +
    `var SnapshotAccounting = (function () {\n${accounting}\n` +
    `return { summarizeCashFlows, calculateUnitAccounting };\n})();\n` +
    `var SnapshotReconciliation = (function () {\n${reconciliation}\nreturn { activeReconciliation, tradeCashTotals };\n})();\n` +
    `var SnapshotPortfolio = (function () {\n${portfolio}\nreturn { calculatePortfolio };\n})();\n` +
    `var SnapshotBuilder = (function () {\n${snapshot}\nreturn { buildSnapshot };\n})();\n\n${adapter}`;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const destination = new URL('../dist/apps-script/', import.meta.url);
  mkdirSync(destination, { recursive: true });
  writeFileSync(new URL('snapshot.gs', destination), buildAppsScript());
  console.log('Built dist/apps-script/snapshot.gs (no credentials).');
}
