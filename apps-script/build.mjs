import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';

export function buildAppsScript() {
  const accounting = readFileSync(new URL('../src/lib/accounting.js', import.meta.url), 'utf8')
    .replaceAll('export function ', 'function ')
    .replaceAll('.at(-1)', '.slice(-1)[0]');
  const adapter = readFileSync(new URL('./snapshot.gs', import.meta.url), 'utf8');
  return `// Generated by npm run build:snapshot. Contains no Firebase credentials.\n` +
    `var SnapshotAccounting = (function () {\n${accounting}\n` +
    `return { summarizeCashFlows, calculateUnitAccounting };\n})();\n\n${adapter}`;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const destination = new URL('../dist/apps-script/', import.meta.url);
  mkdirSync(destination, { recursive: true });
  writeFileSync(new URL('snapshot.gs', destination), buildAppsScript());
  console.log('Built dist/apps-script/snapshot.gs (no credentials).');
}
